"""Tables for the post hoc analyses (plan/posthoc-v4-tierA.md).

Reads results_v2/v4/posthoc_v4_gate2.json, posthoc_v4_gate1.json and
posthoc_v4_gate2_excl_limiting.json (aggregate statistics only) and writes
manuscript/posthoc_table_main.tex (main-text Table 5) and
manuscript/supp_note9_tables.tex (Supplementary Note 9). Nothing is typed by hand.

Usage:
    python scripts/gen_posthoc_tables.py
"""

import json
import logging
from pathlib import Path
from typing import Dict, List

logger = logging.getLogger(__name__)
RES = Path("results_v2/v4")
MAN = Path("manuscript")
EXPLAINERS = (("qwen2.5:14b", "qwen2.5:14b"), ("qwen2.5:32b", "qwen2.5:32b"),
              ("qwen2.5:72b-instruct-q3_K_M", "qwen2.5:72b"), ("gemma3:27b", "gemma3:27b"),
              ("gpt-oss:20b", "gpt-oss:20b"))


def d(a: Dict[str, object]) -> str:
    lo, hi = a["ci95"]
    return f"${a['est']:+.3f}$ [${lo:+.3f}$, ${hi:+.3f}$]"


def table(caption: str, label: str, cols: str, header: str, rows: List[str]) -> str:
    return (f"\\begin{{table}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\small\n"
            f"\\resizebox{{\\ifdim\\width>\\textwidth\\textwidth\\else\\width\\fi}}{{!}}{{%\n"
            f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{header} \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")


def main() -> None:
    g2 = json.load(open(RES / "posthoc_v4_gate2.json"))
    g1 = json.load(open(RES / "posthoc_v4_gate1.json"))
    ex = json.load(open(RES / "posthoc_v4_gate2_excl_limiting.json"))

    rows = []
    for key, name in EXPLAINERS:
        x = g2["explainers"][key]["taxai"]
        dis = (x["dissent_rate_events"] + x["dissent_rate_nonevents"]) / 2
        inc = x["incremental_firth"]
        tl = inc.get("too_low")
        tl_s = f"${tl['coef']:+.2f}$ [${tl['ci95'][0]:+.2f}$, ${tl['ci95'][1]:+.2f}$]" if tl else "---"
        rows.append(f"{name} & {x['auroc']:.3f} & {x['max_attainable_auroc']:.3f} & {100 * dis:.1f}\\% & "
                    f"{d(x['minus_rule_control'])} & {x['by_split']['test']:.3f} & {tl_s} \\\\")
    main_tab = table(
        "\\textbf{Post hoc analyses of the explainer verdicts} (ventilation, LOW labels, $n = 400$; TAXAI condition). "
        "Maximum attainable: the highest AUROC possible given the explainer's observed verdict counts. Dissent: share "
        "of verdicts other than ``about right''. Minus rule control: paired AUROC difference with bootstrap 95\\% CI. "
        "Test only: AUROC among the 188 test cases. ``Too low'' coefficient: Firth-penalized logistic regression "
        "adjusting for logit(model~A), with 95\\% CI; categories with fewer than five cases were pooled with the "
        "reference (Supplementary Note~9).",
        "tab:posthoc", "@{}lcccccc@{}",
        "\\textbf{Explainer} & \\textbf{AUROC} & \\textbf{Max.\\ attainable} & \\textbf{Dissent} & "
        "\\textbf{Minus rule control} & \\textbf{Test only} & \\textbf{``Too low'' coefficient}", rows)
    (MAN / "posthoc_table_main.tex").write_text(
        "% Generated by scripts/gen_posthoc_tables.py. Do not edit by hand.\n" + main_tab)

    # Supplementary Note 9 tables
    abl = g1["P5_ablation_test"]
    names = {"A+value": f"Model A + value dynamics ({g1['n_value_features']} features)",
             "A+process": f"Model A + measurement process ({g1['n_process_features']} features)",
             "B": "Model B (all dynamics)", "A+permuted": "Model A + permuted dynamics (capacity control)"}
    rows = [f"{names[k]} & {abl[k]['B']:.3f} & {d({'est': abl[k]['diff'], 'ci95': abl[k]['ci95']})} \\\\"
            for k in ("A+value", "A+process", "B", "A+permuted")]
    for st, v in g1["P5_within_strata_test"].items():
        rows.append(f"Model B, within {st} labels ($n = {v['n']:,}$; {v['events']} events) & {v['B']:.3f} & "
                    f"{d({'est': v['diff'], 'ci95': v['ci95']})} \\\\")
    s_abl = table("\\textbf{Source of the ventilation Gate~1 signal} (test set; model~A AUROC "
                  f"{abl['B']['A']:.3f}). Paired bootstrap 95\\% CIs (1,000 resamples).",
                  "tab:s_ablation", "@{}lcc@{}",
                  "\\textbf{Model} & \\textbf{AUROC} & \\textbf{$\\Delta$AUROC vs model~A}", rows)

    p6 = g1["P6_model_A"]
    rows = []
    for lab, c in (("Test, all", p6["test_calibration"]), ("Test, LOW labels", p6["test_LOW_calibration"])):
        rows.append(f"{lab} & {100 * c['observed']:.2f}\\% & {100 * c['mean_predicted']:.2f}\\% & "
                    f"${c['intercept']:+.2f}$ & {c['slope']:.2f} & {c['brier']:.4f} \\\\")
    ta = p6["test_auroc"]
    s_cal = table("\\textbf{Ventilation model~A: calibration.} Test AUROC "
                  f"{ta['est']:.3f} [{ta['ci95'][0]:.3f}, {ta['ci95'][1]:.3f}]; validation AUROC {p6['val_auroc']:.3f}. "
                  "Intercept: calibration-in-the-large (positive means risk underestimated).",
                  "tab:s_calibration", "@{}lccccc@{}",
                  "\\textbf{Set} & \\textbf{Observed} & \\textbf{Mean predicted} & \\textbf{Intercept} & "
                  "\\textbf{Slope} & \\textbf{Brier}", rows)

    e = g1["P7_events"]
    q = e["hours_to_imv_iqr"]
    p7d = g1["P7d_gate1_excluding_limiting_code"]
    rows = [f"Events (eligible patients, all splits) & {e['n_events']:,} \\\\",
            f"Hours from prediction to intubation, median (IQR) & {q[1]} ({q[0]}--{q[2]}) \\\\",
            f"Events within 2 hours of the prediction time & {100 * e['within_2h']:.1f}\\% \\\\",
            f"Non-invasive ventilation or high-flow oxygen, events / non-events & {100 * e['niv_hfnc_events']:.1f}\\% / "
            f"{100 * e['niv_hfnc_nonevents']:.1f}\\% \\\\",
            f"DNR/DNI or comfort measures before prediction, events / non-events & {e['limiting_code_events']} / "
            f"{e['limiting_code_nonevents']:,} \\\\",
            f"Non-events: died within 24 hours / left the ICU within 24 hours & {e['nonevents_death_24h']} / "
            f"{e['nonevents_icu_out_24h']:,} (of {e['n_nonevents']:,}) \\\\",
            f"Gate~1 excluding limiting code status ($n$ excluded {p7d['n_excluded']:,}) & "
            f"{d({'est': p7d['diff'], 'ci95': p7d['ci95']})} \\\\"]
    for key, name in EXPLAINERS:
        rows.append(f"Gate~2 excluding limiting code status ($n = {ex['n']}$): {name} TAXAI AUROC & "
                    f"{ex['explainers'][key]['taxai']['auroc']:.3f} \\\\")
    s_ev = table("\\textbf{Ventilation outcome characterization and code-status sensitivity analysis.}",
                 "tab:s_events", "@{}lc@{}", "\\textbf{Quantity} & \\textbf{Value}", rows)

    rows = []
    for key, name in EXPLAINERS:
        for c, x in g2["explainers"][key].items():
            inc = x["incremental_firth"]
            tl = inc.get("too_low")
            tl_s = f"${tl['coef']:+.2f}$ [${tl['ci95'][0]:+.2f}$, ${tl['ci95'][1]:+.2f}$]" if tl else "---"
            lrp = f"{inc['lr_p']:.3f}" if inc.get("lr_p") is not None else "---"
            pooled = ", ".join(inc.get("pooled_into_reference", [])) or "none"
            rows.append(f"{name} & {c.replace('_', ' ')} & {x['spearman_with_pA'] if x['spearman_with_pA'] is not None else '---'} & "
                        f"{x['stratified_auroc_pA_tertiles']} & {inc['reference']} & {pooled} & {tl_s} & {lrp} & "
                        f"{'yes' if inc['added_information'] else 'no'} \\\\")
    s_inc = table("\\textbf{Verdicts and model~A's probability} (ventilation, LOW labels). Spearman correlation of the "
                  "verdict score with model~A's probability; verdict AUROC within tertiles of model~A's probability "
                  "(weighted average); Firth model of the outcome on logit(model~A) and verdict indicators. Added "
                  "information: likelihood-ratio $p < 0.05$ and a ``too low'' coefficient with 95\\% CI above 0.",
                  "tab:s_incremental", "@{}llccllccc@{}",
                  "\\textbf{Explainer} & \\textbf{Condition} & \\textbf{$\\rho$ with $p_A$} & \\textbf{AUROC within tertiles} & "
                  "\\textbf{Reference} & \\textbf{Pooled} & \\textbf{``Too low'' coef.} & \\textbf{LR $p$} & \\textbf{Added}", rows)

    bs = g2["by_split"]
    rows = [f"{sp} & {v['n']} ({v['events']}) & {v['pA']:.3f} & {v['pB']:.3f} & {d(v['B_minus_A'])} & {v['rule_control']:.3f} \\\\"
            for sp, v in (("Validation", bs["val"]), ("Test", bs["test"]))]
    rows.append(f"All & {g2['n']} ({g2['events']}) & --- & --- & {d(g2['B_minus_A'])} & {g2['rule_control']['est']:.3f} \\\\")
    s_split = table("\\textbf{Gate~2 sample, LOW labels, by split.} Paired bootstrap 95\\% CIs.", "tab:s_split",
                    "@{}lccccc@{}", "\\textbf{Split} & \\textbf{$n$ (events)} & \\textbf{Model~A} & \\textbf{Model~B} & "
                    "\\textbf{B $-$ A} & \\textbf{Rule control}", rows)

    intro = ("These analyses were specified and hashed after the registered analyses were complete and before computation "
             "(\\texttt{plan/posthoc-v4-tierA.md}, SHA-256 recorded 2026-10-09 16:13 EDT). They are post hoc and do not "
             "change any registered classification. Two deviations concerned sparse verdict categories in the Firth "
             "models. The second changed the classification for gpt-oss:20b TAXAI after the first result had been seen "
             "(likelihood-ratio $p = 0.068$, not meeting the criterion, under the first handling; $p = 0.010$, meeting "
             "it, after pooling categories with fewer than five cases). Both are reported, and the finding is treated "
             "as fragile.\n\n")
    (MAN / "supp_note9_tables.tex").write_text("% Generated by scripts/gen_posthoc_tables.py. Do not edit by hand.\n"
                                               + intro + "\n".join([s_split, s_inc, s_abl,
                                                                    s_cal, s_ev]))
    logger.info("wrote posthoc tables")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    main()
